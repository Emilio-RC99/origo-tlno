#!/usr/bin/env python3
"""Code generator for the Cartesian->spherical transform tables.

The spherical result for a shell-pair block is

    M_sph = Csc_a^T @ M_cart @ Csc_b ,

where Csc maps the (L+1)(L+2)/2 Cartesian components of a shell to its 2L+1
real solid-harmonic components.  Csc depends on the Cartesian normalization:
TLNO uses *unit-diagonal* Cartesian normalization (<phi|phi> = 1 for every
component), whereas PySCF's cart2sph_coeff assumes PySCF's Cartesian norm.

The bridge (validated end-to-end in bench_cart_vs_sph.py to ~1e-11) is

    Csc = diag(scale) @ C_pyscf ,   scale = sqrt(diag(int1e_ovlp_cart)) ,

and `scale` is a pure number per Cartesian component (ratio of double
factorials), independent of the exponent/contraction.  So Csc is a fixed
per-L table.  This script extracts it once from PySCF, asserts that PySCF's
Cartesian ordering matches TLNO's descending-lexicographic order
(cartesian_tuples_for_total_L), self-checks Csc^T S_tlno Csc == S_sph, and
emits the sparse triples as a C++ header.

Run from anywhere; writes cart2sph_tables.hpp next to this script.
Regenerate only when extending L_MAX or changing the convention.
"""
from __future__ import annotations

import datetime
from pathlib import Path

import numpy as np
from pyscf import gto

L_MAX = 4 # s,p,d,f,g - covers def2-TZVP (f) and def2-QZVP (g)
COEFF_TOL = 1e-14 # drop coefficients below this in the sparse table

def descending_lex_tuples(L: int):
    """TLNO's cartesian_tuples_for_total_L ordering (basis/cartesian_shells.hpp)."""
    out = []
    for ax in range(L, -1, -1): 
        for ay in range(L - ax, -1, -1):
            out.append((ax, ay, L - ax - ay))
    return out

def pyscf_cart_tuples(L: int):
    """Cartesian (lx,ly,lz) order PySCF uses for a single shell of momentum L."""
    mol = gto.M(atom = "He 0 0 0", basis = {"He": [[L, [1.0, 1.0]]]}, 
                cart = True, spin = 0 if L % 2 == 0 else None, verbose = 0)
    tuples = []
    for lab in mol.cart_labels(fmt = False): # (atom, sym, n + l, m-string)
        ml = lab[3] # e.g. 'xxy'
        t = (ml.count("x"), ml.count("y"), ml.count("z"))
        tuples.append(t)
    return tuples

def csc_for_L(L: int):
    """Return (Csc [n_cart x n_sph], S_sph [n_sph x n_sph]) for momentum L."""
    mol = gto.M(atom = "He 0 0 0", basis = {"He": [[L, [1.0, 1.0]]]}, 
                cart = True, verbose = 0)
    s_cart = mol.intor("int1e_ovlp_cart")              # PySCF cart overlap
    C = mol.cart2sph_coeff(normalized = "sp")         # n_cart x n_sph
    scale = np.sqrt(np.diag(s_cart))                  # per-component pure number
    Csc = scale[:, None] * C
    # TLNO unit-diagonal cart overlap and the spherical reference:
    Dinv = np.diag(1.0 / scale)
    s_tlno = Dinv @ s_cart @ Dinv
    msph = gto.M(atom="He 0 0 0", basis={"He": [[L, [1.0, 1.0]]]},
                 cart = False, verbose = 0)
    s_sph_ref = msph.intor("int1e_ovlp_sph")
    s_sph_via = Csc.T @ s_tlno @ Csc
    err = np.max(np.abs(s_sph_via - s_sph_ref))
    assert err < 1e-12, f"L = {L}: Csc self-check failed, maxdiff = {err:.2e}"
    return Csc, s_sph_ref

def main():
    here = Path(__file__).resolve().parent
    out = here / "cart2sph_tables.hpp"

    blocks = {}
    for L in range(L_MAX + 1):
        tl = descending_lex_tuples(L)
        py = pyscf_cart_tuples(L)
        assert tl == py, (
            f"L = {L}: PySCF cart order {py} != TLNO descending-lex {tl}; "
            "a row permutation would be required."
        )
        Csc, _ = csc_for_L(L)
        n_cart, n_sph = Csc.shape
        assert n_cart == (L + 1) * (L + 2) // 2
        assert n_sph == 2 * L + 1
        triples = []
        for c in range(n_cart):
            for s in range(n_sph):
                v = float(Csc[c, s])
                if abs(v) > COEFF_TOL:
                    triples.append((s, c, v))
        blocks[L] = triples

    stamp = datetime.date.today().isoformat()
    lines = []
    lines.append("// cart2sph_tables.hpp — GENERATED by gen_cart2sph_tables.py; DO NOT EDIT.")
    lines.append(f"// Regenerated {stamp}. Cartesian order: descending-lex (ax:L..0),")
    lines.append("// matching cartesian_tuples_for_total_L. Spherical order: PySCF real")
    lines.append("// solid harmonics. Coefficients fold TLNO unit-diagonal normalization")
    lines.append("// (Csc = diag(sqrt(diag(S_cart))) @ cart2sph_coeff). Self-checked to <1e-12.")
    lines.append("#ifndef TLNO_CORE_SHELL_CART2SPH_TABLES_HPP")
    lines.append("#define TLNO_CORE_SHELL_CART2SPH_TABLES_HPP")
    lines.append("")
    lines.append("namespace tlno::core::shell::cart2sph_detail {")
    lines.append("")
    lines.append("struct C2STriple {")
    lines.append("    int sph;")
    lines.append("    int cart;")
    lines.append("    double coeff;")
    lines.append("};")
    lines.append("")
    lines.append(f"inline constexpr int kMaxL = {L_MAX};")
    lines.append("")
    for L in range(L_MAX + 1):
        triples = blocks[L]
        lines.append(f"inline constexpr C2STriple kC2S_L{L}[] = {{")
        for (s, c, v) in triples:
            lines.append(f"    {{{s}, {c}, {v!r}}},")
        lines.append("};")
    lines.append("")
    lines.append("struct C2SBlock {")
    lines.append("    const C2STriple* data;")
    lines.append("    int count;")
    lines.append("};")
    lines.append("")
    lines.append("inline constexpr C2SBlock kC2SBlocks[] = {")
    for L in range(L_MAX + 1):
        n = len(blocks[L])
        lines.append(f"    {{kC2S_L{L}, {n}}},")
    lines.append("};")
    lines.append("")
    lines.append("} // namespace tlno::core::shell::cart2sph_detail")
    lines.append("")
    lines.append("#endif")
    out.write_text("\n".join(lines) + "\n")
    total = sum(len(b) for b in blocks.values())
    print(f"wrote {out} ({total} triples, L = 0..{L_MAX})")
    for L in range(L_MAX + 1):
        print(f"  L = {L}: n_cart = {(L + 1) * (L + 2) // 2} n_sph = {2 * L + 1} " 
              f"nnz = {len(blocks[L])}")

if __name__ == "__main__":
    main()
